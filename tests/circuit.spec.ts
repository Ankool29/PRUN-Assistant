import { expect, test } from '@playwright/test'
import { readFileSync } from 'node:fs'

const snapshot = JSON.parse(readFileSync(new URL('../public/data/fio.json', import.meta.url), 'utf8'))

test('circuit multidevise tactile avec conversion FXOB puis portefeuille sans change', async ({ page }) => {
  const current = new Date()
  const observedAt = current.toISOString()
  const from = { ...snapshot.markets[0], ticker: 'AL', exchange: 'AI1', currency: 'AIC', observedAt, last: null, average: null,
    sells: [{ price: 4000, quantity: 10 }], buys: [] }
  const to = { ...from, exchange: 'CI1', currency: 'CIS', sells: [], buys: [{ price: 3000, quantity: 10 }] }
  await page.route('**/data/fio.json', route => route.fulfill({ json: { ...snapshot, collectedAt: observedAt, markets: [from, to] } }))
  await page.goto('./#scanner')
  await page.getByRole('combobox', { name: 'Marché de stationnement' }).selectOption('AI1')
  await page.getByRole('button', { name: 'Circuits multidevises' }).tap()
  await page.getByText('Frais, transport, quantités et change', { exact: true }).tap()
  await page.getByRole('spinbutton', { name: 'Frais d’achat (%)' }).fill('0')
  await page.getByRole('spinbutton', { name: 'Frais de vente (%)' }).fill('0')
  await page.getByRole('spinbutton', { name: 'Trajet chargé, montant fixe (AIC)' }).fill('20')
  await page.getByRole('spinbutton', { name: 'Trajet chargé, par unité (AIC)' }).fill('0')
  const unknown = page.getByRole('region', { name: 'Rentabilité indéterminée' })
  await unknown.getByText('AI1 vers CI1', { exact: true }).tap()
  await expect(unknown.getByText(/Solde en CIS/)).toBeVisible()
  await page.getByText('Relevés de change FXOB', { exact: true }).tap()
  await page.getByRole('combobox', { name: 'Devise de base FXOB' }).selectOption('CIS')
  await page.getByRole('spinbutton', { name: 'Cours acheteur' }).fill('1.8')
  await page.getByRole('spinbutton', { name: 'Lots acheteurs' }).fill('3')
  await page.getByRole('spinbutton', { name: 'Cours vendeur' }).fill('2')
  await page.getByRole('spinbutton', { name: 'Lots vendeurs' }).fill('2')
  await page.getByRole('spinbutton', { name: 'Frais de change (%)' }).fill('0')
  await page.getByRole('spinbutton', { name: 'Frais fixes par ordre (AIC)' }).fill('10')
  await page.getByLabel('Observation du carnet (UTC)').fill(observedAt.slice(0, 16))
  await page.getByRole('checkbox', { name: /relevé ces cours/ }).check()
  await page.getByRole('button', { name: 'Enregistrer le relevé' }).tap()
  await expect(page.getByText('Relevé enregistré dans ce navigateur.')).toBeVisible()
  const profitable = page.getByRole('region', { name: 'Circuits rentables', exact: true })
  const card = profitable.locator('details')
  await card.locator('summary').tap()
  await expect(card.getByText(/Capital final fermé/)).toBeVisible()
  await expect(card.getByText(/101.370,00 AIC/).first()).toBeVisible()
  await expect(card.getByText(/Avantage du commerce sur l’aller-retour monétaire/)).toBeVisible()
  await page.getByRole('combobox', { name: 'Règlement du circuit' }).selectOption('hold')
  if (await card.getAttribute('open') === null) await card.locator('summary').tap()
  await expect(card.getByText('Aucune conversion simulée.')).toBeVisible()
  await expect(card.getByText(/Marge indicative sur les flux de trésorerie/)).toBeVisible()
  expect(await page.evaluate(() => document.documentElement.scrollWidth)).toBeLessThanOrEqual(await page.evaluate(() => innerWidth))
  await page.reload()
  await page.getByRole('button', { name: 'Circuits multidevises' }).tap()
  await page.getByText('Relevés de change FXOB', { exact: true }).tap()
  await page.getByRole('combobox', { name: 'Devise de base FXOB' }).selectOption('CIS')
  await expect(page.getByRole('spinbutton', { name: 'Cours acheteur' })).toHaveValue('1.8')
})
